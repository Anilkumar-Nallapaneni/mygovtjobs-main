#!/usr/bin/env node
/**
 * Keep frontend/src/data/homeShellStats.ts honest vs live-jobs.json.
 * Run after export/clean so hero shell numbers match the gated catalog.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { writeFileAtomic } from './write-file-atomic.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const livePath = path.join(root, 'frontend/public/data/live-jobs.json')
const outPath = path.join(root, 'frontend/src/data/homeShellStats.ts')

const payload = JSON.parse(fs.readFileSync(livePath, 'utf8'))
const items = Array.isArray(payload.items) ? payload.items : []
const live = items.length
const vacancies = items.reduce((sum, row) => sum + (Number(row?.vacancies) || 0), 0)
const withVac = items.filter((row) => Number(row?.vacancies) > 0).length
const orgs = new Set(
  items.map((row) => String(row?.dept || row?.organization || '').trim()).filter(Boolean)
).size
const states = new Set(
  items.flatMap((row) => (Array.isArray(row?.state_codes) ? row.state_codes : [])).filter(Boolean)
).size
const stateListings = items.filter(
  (row) => Array.isArray(row?.state_codes) && row.state_codes.length > 0
).length
const hotNew = items.filter((row) => {
  const tags = row?.tags || row?.badges || []
  if (Array.isArray(tags) && tags.some((t) => /hot|new/i.test(String(t)))) return true
  const pub = row?.published_at ? Date.parse(row.published_at) : NaN
  if (!Number.isFinite(pub)) return false
  return Date.now() - pub < 7 * 24 * 60 * 60 * 1000
}).length

const contents = `import type { CatalogStats } from '@/utils/liveJobsPipeline'
import type { HeadlineStats } from '@/utils/headlineStats'

/** Snapshot-aligned totals — regenerated by scripts/sync-home-shell-stats.mjs after export/clean. */
export const HOME_SHELL_HEADLINE_STATS: HeadlineStats = {
  notifications: ${live},
  vacancies: ${vacancies},
  orgs: ${Math.max(orgs, 1)},
}

/** Avoid importing full ORG_INDEX / OFFICIAL_SITES just for counts on the home shell. */
export const HOME_SHELL_ORG_COUNT = ${Math.max(orgs, 1)}
export const HOME_SHELL_OFFICIAL_SOURCE_COUNT = 153

export const HOME_SHELL_CATALOG_STATS: CatalogStats = {
  totalNotices: ${live},
  liveNotices: ${live},
  vacancies: ${vacancies},
  noticesWithVacancies: ${withVac},
}

export const HOME_SHELL_HERO_STATS = {
  posts: ${vacancies},
  withPostCount: ${withVac},
  hotNew: ${hotNew},
  states: ${Math.max(states, 1)},
  stateListings: ${stateListings},
  live: ${live},
}
`

await writeFileAtomic(outPath, contents)
console.log(
  `Synced homeShellStats — live=${live} vacancies=${vacancies} orgs=${orgs} states=${states}`
)
